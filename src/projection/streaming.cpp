using cd = std::complex<double>;
using OmpExceptionGuard = detail::ExceptionGuard;
std::vector<KProjection> ProjectionModel::project_k(const WavecarReader& reader, int k, int first, int count,
                                                    Backend& backend, int block_bands, std::size_t factor_budget_bytes,
                                                    int paw_check_stride) const {
    std::lock_guard<std::mutex> lock(spec_mutex_);
    // One k-point: the parallelism is inside the GEMMs. OpenBLAS uses PROWL's thread count (OpenMP), not its own
    // default (all logical CPUs) or OPENBLAS_NUM_THREADS; inside a parallel region it keeps one thread.
#ifdef _OPENMP
    BlasThreads blas(omp_in_parallel() ? 1 : omp_get_max_threads());
#else
    BlasThreads blas(1);
#endif
    return project_k_with(reader, k, first, count, backend, block_bands, factor_budget_bytes, orb_spec_, proj_spec_,
                          fold_spec_, paw_check_stride);
}

std::vector<std::vector<KProjection>> ProjectionModel::project_many(const WavecarReader& reader,
                                                                    const std::vector<int>& ks, int first, int count,
                                                                    int block_bands, std::size_t factor_budget_bytes,
                                                                    int paw_check_stride) const {
    std::lock_guard<std::mutex> lock(spec_mutex_); // no concurrent single-k use of the member specs
    std::vector<std::vector<KProjection>> out(ks.size());
    if (ks.empty()) return out;
    std::size_t max_ng = 0;
    for (int k : ks)
        max_ng = std::max(max_ng, reader.gvectors(k)->size());
    const std::size_t minimum = max_ng * sizeof(cd) * (reader.encoding() == WavefunctionEncoding::GammaHalf ? 2u : 1u);
    require(factor_budget_bytes >= minimum, ErrorCode::OutOfMemory, "factor budget cannot hold one column");
#ifdef _OPENMP
    const int max_threads = omp_get_max_threads();
#else
    const int max_threads = 1;
#endif
    const int workers =
        static_cast<int>(std::min({ks.size(), static_cast<std::size_t>(max_threads), factor_budget_bytes / minimum}));
    const std::size_t per_worker = factor_budget_bytes / static_cast<std::size_t>(workers);
    BlasThreads blas(1); // parallelism is over k here
    OmpExceptionGuard guard;
#pragma omp parallel num_threads(workers)
    {
        auto be = make_cpu_backend();
        SeparableFactorSpec orb = orb_spec_, proj = proj_spec_, fold = fold_spec_;
#pragma omp for schedule(dynamic)
        for (std::size_t i = 0; i < ks.size(); ++i)
            guard.run([&] {
                out[i] = project_k_with(reader, ks[i], first, count, *be, block_bands, per_worker, orb, proj, fold,
                                        paw_check_stride);
            });
    }
    guard.rethrow();
    return out;
}

std::vector<KProjection> ProjectionModel::project_k_with(const WavecarReader& reader, int k, int first, int count,
                                                         Backend& backend, int block_bands,
                                                         std::size_t factor_budget_bytes, SeparableFactorSpec& orb,
                                                         SeparableFactorSpec& projs, SeparableFactorSpec& fold,
                                                         int paw_check_stride) const {
    require(first >= 0 && count > 0 && first <= reader.header().nbands && count <= reader.header().nbands - first &&
                block_bands >= 0 && paw_check_stride >= 1,
            ErrorCode::InvalidArgument, "invalid projection band range or stride");
    const auto G = reader.gvectors(k);
    const Vec3 kf = reader.kpoint(0, k).k_frac;
    const int ng = static_cast<int>(G->size());
    check_q_range(kf, *G, false);
    check_q_range(kf, *G, true);
    // Factor column blocks bounded by the budget (complex128 columns of length ng, doubled
    // transiently for the packed real copy on the Gamma path). Factors are generated by the
    // backend (host or device) for each block.
    const bool gamma = reader.encoding() == WavefunctionEncoding::GammaHalf;
    const std::size_t col_bytes = static_cast<std::size_t>(ng) * sizeof(cd) * (gamma ? 2u : 1u);
    require(factor_budget_bytes >= col_bytes, ErrorCode::OutOfMemory, "factor budget cannot hold one column");
    backend.set_factor_memory_limit(factor_budget_bytes);
    const int cols_per_block = static_cast<int>(
        std::min<std::size_t>(static_cast<std::size_t>(std::max(norb(), nproj())), factor_budget_bytes / col_bytes));
    const int bs = block_bands > 0 ? block_bands : count;
    std::vector<double> w(ng);
    for (int g = 0; g < ng; ++g)
        w[g] = ((*G)[g][0] == 0 && (*G)[g][1] == 0 && (*G)[g][2] == 0) ? 1.0 : 2.0;

    // Folded projection (A_AE directly, B of sampled bands; header): bands n % stride == 0 and the last band
    const bool folded = paw_check_stride > 1 && !fold.lm.empty();
    std::vector<int> samples;
    if (folded) {
        for (int n = 0; n < count; n += paw_check_stride)
            samples.push_back(n);
        if (count > 0 && samples.back() != count - 1) samples.push_back(count - 1);
    }
    for (auto* sp : {&orb, &projs, &fold}) {
        sp->k = kf;
        sp->G = G->data();
        sp->ng = ng;
    }
    // Band blocks in (spin, band) order. Outside a parallel region the next block is read by a background thread
    // while the backend projects the current one (half-size blocks keep the resident data within one block's
    // budget); WAVECAR reading is then the only serial part.
    // Only for large blocks: on k meshes (many small blocks) a thread per block costs more than it hides.
    const bool large = static_cast<double>(ng) * std::min(bs, count) * sizeof(cd) > 64e6;
#ifdef _OPENMP
    const bool prefetch = large && !omp_in_parallel();
#else
    const bool prefetch = large;
#endif
    const int bstep = prefetch && bs > 1 ? (bs + 1) / 2 : bs;
    struct Item {
        int s, b0, nb;
    };
    std::vector<Item> items;
    for (int s = 0; s < reader.header().nspin; ++s)
        for (int b0 = 0; b0 < count; b0 += bstep)
            items.push_back({s, b0, std::min(bstep, count - b0)});
    // two block buffers, reused (no reallocation or zero fill per block); block i lives in bufs[i % 2]
    WavefunctionBlock bufs[2];
    const std::size_t buffer_count = prefetch ? 2 : 1;
    auto fetch = [&reader, k, first, &bufs, buffer_count](std::size_t i, Item it) {
        reader.read_block_into(it.s, k, first + it.b0, it.nb, bufs[i % buffer_count]);
    };
    std::future<void> pending;
    if (prefetch && !items.empty()) pending = std::async(std::launch::async, fetch, std::size_t{0}, items[0]);
    std::vector<KProjection> out;
    KProjection kp;
    std::size_t next_sample = 0;           // first entry of samples not yet projected (this spin)
    std::vector<std::complex<double>> sub; // coefficients of the sampled bands of one block
    // projections onto factor columns [c0, c0 + n) of sp, in budget-sized column blocks, into dst rows [c0', ...)
    // and columns [col0, col0 + ncols)
    auto project_columns = [&](const SeparableFactorSpec& sp, int c0, int n, Eigen::MatrixXcd& dst, int col0,
                               int ncols) {
        for (int c = 0; c < n; c += cols_per_block) {
            const int nc = std::min(cols_per_block, n - c);
            if (gamma) {
                Eigen::MatrixXd r(nc, ncols);
                backend.project_separable(sp, c0 + c, nc, nullptr, r.data());
                dst.block(c, col0, nc, ncols) = r.cast<cd>();
            } else {
                Eigen::MatrixXcd r(nc, ncols);
                backend.project_separable(sp, c0 + c, nc, r.data(), nullptr);
                dst.block(c, col0, nc, ncols) = r;
            }
        }
    };
    for (std::size_t i = 0; i < items.size(); ++i) {
        const auto [s, b0, nb] = items[i];
        if (b0 == 0) {
            kp = KProjection{};
            kp.real_gauge = gamma;
            kp.pw_norm.resize(count);
            if (folded) {
                kp.a_ae.resize(norb(), count);
                kp.b.resize(nproj(), static_cast<Eigen::Index>(samples.size()));
                kp.paw_bands = samples;
                kp.paw_norm.resize(samples.size());
                next_sample = 0;
            } else {
                kp.a_soft.resize(norb(), count);
                kp.b.resize(nproj(), count);
                kp.paw_norm.resize(count);
            }
        }
        if (prefetch)
            pending.get();
        else
            fetch(i, items[i]);
        const WavefunctionBlock& blk = bufs[i % buffer_count];
        // block i - 1 (the other buffer) is fully consumed: read block i + 1 into it
        if (prefetch && i + 1 < items.size()) pending = std::async(std::launch::async, fetch, i + 1, items[i + 1]);
        backend.load_coefficients(blk.coefficients.data(), ng, nb, gamma ? w.data() : nullptr);
        if (!folded) {
            project_columns(orb, 0, orb.nf(), kp.a_soft, b0, nb);
            project_columns(projs, 0, projs.nf(), kp.b, b0, nb);
        } else {
            project_columns(fold, 0, norb(), kp.a_ae, b0, nb);
            // projector amplitudes of the sampled bands of this block (contiguous in samples)
            const std::size_t s0 = next_sample;
            while (next_sample < samples.size() && samples[next_sample] < b0 + nb)
                ++next_sample;
            const int ns = static_cast<int>(next_sample - s0);
            if (ns > 0) {
                sub.resize(static_cast<std::size_t>(ng) * ns);
                for (int j = 0; j < ns; ++j)
                    std::copy_n(blk.band(samples[s0 + j] - b0), ng, sub.data() + static_cast<std::size_t>(j) * ng);
                backend.load_coefficients(sub.data(), ng, ns, gamma ? w.data() : nullptr);
                project_columns(fold, norb(), nproj(), kp.b, static_cast<int>(s0), ns);
            }
        }
        const auto pw = blk.plane_wave_norms();
        for (int n = 0; n < nb; ++n)
            kp.pw_norm[b0 + n] = pw[n];
        if (b0 + nb == count) { // last block of this spin
            if (folded) {
                const Eigen::VectorXd q = paw_q_norms(kp.b);
                for (std::size_t j = 0; j < samples.size(); ++j)
                    kp.paw_norm[j] = kp.pw_norm[samples[j]] + q(j);
            } else {
                finish_paw(kf, kp);
            }
            kp.factor_peak_bytes = backend.factor_memory_stats().peak_bytes;
            out.push_back(std::move(kp));
        }
    }
    return out;
}

KProjection ProjectionModel::project(const WavefunctionBlock& blk, Backend& backend) const {
    BlasThreads policy;
    require(blk.gvectors && blk.ng() > 0 && blk.band_count > 0 &&
                blk.coefficients.size() == blk.ng() * static_cast<std::size_t>(blk.band_count),
            ErrorCode::InvalidArgument, "invalid wavefunction block dimensions");
    require(blk.encoding != WavefunctionEncoding::Spinor, ErrorCode::UnsupportedFeature,
            "spinor projection unsupported");
    const auto& G = *blk.gvectors;
    const int ng = static_cast<int>(G.size()), nb = blk.band_count;
    check_q_range(blk.k_frac, G, false);
    check_q_range(blk.k_frac, G, true);
    KProjection out;
    out.real_gauge = blk.encoding == WavefunctionEncoding::GammaHalf;
    out.a_soft.resize(norb(), nb);
    out.b.resize(nproj(), nb);
    std::vector<double> w(ng);
    for (int g = 0; g < ng; ++g)
        w[g] = (G[g][0] == 0 && G[g][1] == 0 && G[g][2] == 0) ? 1.0 : 2.0;
    {
        std::lock_guard<std::mutex> lock(spec_mutex_);
        for (auto* sp : {&orb_spec_, &proj_spec_}) {
            sp->k = blk.k_frac;
            sp->G = G.data();
            sp->ng = ng;
        }
        backend.load_coefficients(blk.coefficients.data(), ng, nb, out.real_gauge ? w.data() : nullptr);
        if (out.real_gauge) {
            Eigen::MatrixXd as(norb(), nb), bs(nproj(), nb);
            backend.project_separable(orb_spec_, 0, norb(), nullptr, as.data());
            backend.project_separable(proj_spec_, 0, nproj(), nullptr, bs.data());
            out.a_soft = as.cast<cd>();
            out.b = bs.cast<cd>();
        } else {
            backend.project_separable(orb_spec_, 0, norb(), out.a_soft.data(), nullptr);
            backend.project_separable(proj_spec_, 0, nproj(), out.b.data(), nullptr);
        }
    }
    out.pw_norm = blk.plane_wave_norms();
    out.paw_norm.resize(nb);
    finish_paw(blk.k_frac, out);
    return out;
}

