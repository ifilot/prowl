"""Export bonding.h5 in LOBSTER-compatible text formats for existing tooling (pymatgen, LobsterPy).

Written files: COHPCAR.lobster, COOPCAR.lobster, ICOHPLIST.lobster, ICOOPLIST.lobster,
CHARGE.lobster. PROWL's native bonding.h5 remains authoritative. Differences from files written
by LOBSTER itself, all documented in SCIENCE.md:

* curves use PROWL's broadening (Gaussian: sigma = standard deviation at grid points, or linear
  tetrahedron bin averages), always written relative to E_F as LOBSTER readers expect;
* IpCOHP columns are the running integral of the broadened curve, while ICOHPLIST values are the
  exact occupation-weighted sums (equal to LOBSTER's "ICOHP at E_F" definition);
* bonds are those selected in PROWL, each pair (A, B, R) once.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np


def _cumtrapz(y: np.ndarray, x: np.ndarray) -> np.ndarray:
    out = np.zeros_like(y)
    out[..., 1:] = np.cumsum(0.5 * (y[..., 1:] + y[..., :-1]) * np.diff(x), axis=-1)
    return out


def write_lobster_format(h5path: str | Path, outdir: str | Path) -> list[Path]:
    import h5py

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    with h5py.File(h5path, "r") as f:
        E = f["analyses/cohp/energies"][()]
        cohp, coop = f["analyses/cohp/cohp"][()], f["analyses/coop/coop"][()]
        icohp, icoop = f["analyses/cohp/icohp"][()], f["analyses/coop/icoop"][()]
        has_cobi = "analyses/cobi" in f  # files written before COBI support lack this group
        cobi = f["analyses/cobi/cobi"][()] if has_cobi else None
        icobi = f["analyses/cobi/icobi"][()] if has_cobi else None
        atoms = f["analyses/cohp/bond_atoms"][()]
        trans = f["analyses/cohp/bond_translation"][()]
        dist = f["analyses/cohp/bond_distance"][()]
        elements = [x.decode() for x in f["structure/elements"][()]]
        mull = f["analyses/charges/mulliken_charge"][()]
        lowd = f["analyses/charges/lowdin_charge"][()]
        prov = json.loads(f["meta/provenance_json"][()])
        diag = json.loads(f["reconstruction/diagnostics_json"][()])
        efermi = float(f["meta"].attrs.get("efermi_ev", float("nan")))
    config = prov.get("config", {})
    broadening = config.get("broadening", "gaussian")
    if config.get("reference", "fermi") == "absolute":
        # LOBSTER files are referenced to E_F (readers add E_F back): shift absolute grids
        if not np.isfinite(efermi):
            raise ValueError("absolute energy grid but no Fermi energy stored; cannot write LOBSTER format")
        E = E - efermi
    nspin, nb, npts = cohp.shape
    name = lambda a: f"{elements[a]}{a + 1}"
    written = []

    def curves(kind: str, data: np.ndarray, fname: str):
        if broadening == "tetrahedron":  # bin averages: the running integral is the exact cumulative sum
            integ = np.cumsum(data, axis=-1) * (E[1] - E[0])
        else:
            integ = _cumtrapz(data, E)
        lines = [f"ESCALE ; p{kind} file generated by PROWL (LOBSTER-compatible layout). Energy is shifted such "
                 "that the Fermi level lies at 0 eV.",
                 f"{nb + 1:10d}{nspin:11d}{npts:11d}{E[0]:14.5e}{E[-1]:14.5e}{efermi:14.5e}",
                 "Average"]
        lines += [f"No.{i + 1}:{name(a)}->{name(b)}({float(d)!r})" for i, ((a, b), d) in enumerate(zip(atoms, dist))]
        for j in range(npts):
            row = [E[j]]
            for s in range(nspin):
                row += [data[s, :, j].mean() if nb else 0.0, integ[s, :, j].mean() if nb else 0.0]
                for i in range(nb):
                    row += [data[s, i, j], integ[s, i, j]]
            lines.append("".join(f"{v:15.5e}" for v in row))
        p = outdir / fname
        p.write_text("\n".join(lines) + "\n")
        written.append(p)

    def lists(kind: str, values: np.ndarray, fname: str):
        head = f"  {kind}#    atomMU    atomNU   distance   translation   " + "    ".join(
            f"I{kind} (at) eF" for _ in range(nspin))
        sub = " " * 58 + "".join(f"for spin {s + 1}       " for s in range(nspin))
        lines = [head, sub]
        for i, ((a, b), d, R) in enumerate(zip(atoms, dist, trans)):
            lines.append(f"{i + 1:7d}{name(a):>10s}{name(b):>10s}{d:11.5f}{R[0]:6d}{R[1]:4d}{R[2]:4d}" +
                         "".join(f"{values[s, i]:16.5f}" for s in range(nspin)))
        p = outdir / fname
        p.write_text("\n".join(lines) + "\n")
        written.append(p)

    curves("COHP", cohp, "COHPCAR.lobster")
    curves("COOP", coop, "COOPCAR.lobster")
    lists("COHP", icohp, "ICOHPLIST.lobster")
    lists("COOP", icoop, "ICOOPLIST.lobster")
    if has_cobi:
        curves("COBI", cobi, "COBICAR.lobster")
        lists("COBI", icobi, "ICOBILIST.lobster")
    lines = ["MULLIKEN and LOEWDIN POPULATION ANALYSIS (PROWL)", "",
             "  atom#    atom      Mulliken charge       Loewdin charge"]
    for a, (m, l) in enumerate(zip(mull, lowd)):
        lines.append(f"{a + 1:7d}{elements[a]:>8s}{m:21.2f}{l:21.2f} ")
    lines += ["", f"          total{mull.sum():21.2f}{lowd.sum():21.2f} "]
    p = outdir / "CHARGE.lobster"
    p.write_text("\n".join(lines) + "\n")
    written.append(p)
    note = outdir / "README_PROWL.txt"
    note.write_text("Files in LOBSTER-compatible layout written by PROWL from " + str(h5path) + ".\n"
                    "Band window: " + str(diag.get("band_window_note")) + "\n"
                    "PAW mode: " + str(prov.get("config", {}).get("projection")) + "\n"
                    "Curves: " + ("linear tetrahedron, bin averages" if broadening == "tetrahedron" else
                                  "Gaussian, sigma = standard deviation, values at grid points") +
                    "; energies relative to E_F; ICOHPLIST: exact occupation-weighted sums.\n")
    written.append(note)
    return written
